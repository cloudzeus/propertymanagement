async function main() {
  const cats = await db.maintenanceCategory.findMany({ select: { id: true, name: true } });
  const byName = new Map(cats.map((c) => [c.name, c.id]));
  let created = 0, updated = 0, order = 0;
  for (const [catName, items] of Object.entries(CATALOG)) {
    const categoryId = byName.get(catName) ?? null;
    if (!categoryId) console.warn(`κατηγορία δεν βρέθηκε: ${catName}`);
    for (const it of items) {
      order += 10;
      const existing = await db.serviceCatalogItem.findFirst({ where: { name: it.name }, select: { id: true } });
      if (existing) { await db.serviceCatalogItem.update({ where: { id: existing.id }, data: { unit: it.unit, description: it.description ?? null, categoryId, sortOrder: order, active: true } }); updated++; }
      else { await db.serviceCatalogItem.create({ data: { name: it.name, unit: it.unit, description: it.description ?? null, categoryId, sortOrder: order, active: true } }); created++; }
    }
  }
  console.log(`κατάλογος υπηρεσιών: ${created} νέες, ${updated} ενημερώθηκαν`);
}

main().then(() => process.exit(0)).catch((e) => { console.error(e); process.exit(1); });
